import { chromium, expect } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root=fileURLToPath(new URL('..',import.meta.url));
const runtime=join(root,'.chief-local/platform');
const manifest=JSON.parse(await readFile(join(runtime,'manifest.json'),'utf8'));
if (manifest.project!=='chief-platform' || manifest.url!=='http://localhost:18087' || manifest.status!=='ready') throw new Error('Expected independent Chief Platform fixture');
const state=JSON.parse(await readFile(join(runtime,'acceptance-state.json'),'utf8'));
if (!state.origins.some(o=>o.origin===manifest.url && o.localStorage.some(i=>i.name.includes('chiefacceptance')))) throw new Error('Expected synthetic acceptance state');
const evidence=join(root,'docs/verification/evidence');
await mkdir(evidence,{recursive:true});
const base=`${manifest.url}/workbench/chiefacceptance`;
const browser=await chromium.launch({headless:true,channel:'chrome'});
const checks=[];
try {
 const context=await browser.newContext({storageState:state,viewport:{width:1600,height:1000}});
 const page=await context.newPage();page.setDefaultTimeout(20000);
 await page.goto(`${base}/chunter/chunter%3Aspace%3AGeneral%7Cchunter%3Aclass%3AChannel/6ac6abb492587335b11188b5`,{waitUntil:'networkidle'});
 await expect(page.getByText('Chief synthetic human-channel message.',{exact:true}).last()).toBeVisible();
 if (!(await page.getByText('Chief synthetic thread reply.',{exact:true}).isVisible())) await page.getByText('1 reply',{exact:true}).click();
 await expect(page.getByText('Chief synthetic thread reply.',{exact:true})).toBeVisible();
 checks.push('Human channel message and thread reply persist separately from private agent conversations');
 await page.screenshot({path:join(evidence,'chief-platform-human-thread.png')});
 await page.goto(`${base}/tracker/TSK-1`,{waitUntil:'networkidle'});
 await expect(page.getByPlaceholder('Issue title',{exact:true})).toHaveValue('Chief Synthetic Issue');
 await expect(page.locator('.ProseMirror.flex-grow')).toContainText('Synthetic issue description for Chief acceptance.');
 checks.push('Created Tracker issue TSK-1 and rich description persist in a fresh browser context');
 await page.screenshot({path:join(evidence,'chief-platform-tracker.png')});
 await page.goto(`${base}/document/chief-synthetic-document-6ac6ac15ec1dc7ce12045dc6`,{waitUntil:'networkidle'});
 await expect(page.getByPlaceholder('Untitled',{exact:true})).toHaveValue('Chief Synthetic Document');
 await expect(page.locator('.ProseMirror.flex-grow')).toContainText('Chief synthetic editable document.');
 await expect(page.getByRole('button',{name:'Chief Synthetic Teamspace',exact:true})).toBeVisible();
 checks.push('Document teamspace, document title and edited rich body persist in a fresh browser context');
 await page.screenshot({path:join(evidence,'chief-platform-document.png')});
 const partnerState=JSON.parse(await readFile(join(runtime,'acceptance-partner-state.json'),'utf8'));
 if (!partnerState.origins.some(o=>o.origin===manifest.url && o.localStorage.some(i=>i.name.includes('chiefacceptance')))) throw new Error('Expected synthetic partner state');
 const direct=`${base}/chunter/6ac6ad4922224d41ae744a58%7Cchunter%3Aclass%3ADirectMessage`;
 const message=`Chief synthetic DM delivery ${Date.now()}`;
 await page.goto(direct,{waitUntil:'networkidle'});
 await page.locator('[contenteditable=true]').fill(message);
 await page.locator('[contenteditable=true]').press('Enter');
 await expect(page.getByText(message,{exact:true})).toBeVisible();
 const partner=await browser.newContext({storageState:partnerState,viewport:{width:1440,height:1000}});
 const recipient=await partner.newPage();
 await recipient.goto(`${base}/notification`,{waitUntil:'networkidle'});
 await expect(recipient.getByText(message,{exact:true})).toBeVisible();
 checks.push('A new human DM produces an Inbox notification for the separately signed-in recipient');
 await recipient.screenshot({path:join(evidence,'chief-platform-inbox.png')});
 await recipient.goto(direct,{waitUntil:'networkidle'});
 await expect(recipient.getByText(message,{exact:true})).toBeVisible();
 const reply=`Chief synthetic DM reply ${Date.now()}`;
 await recipient.locator('[contenteditable=true]').fill(reply);
 await recipient.locator('[contenteditable=true]').press('Enter');
 await expect(page.getByText(reply,{exact:true})).toBeVisible();
 await page.reload({waitUntil:'networkidle'});
 await expect(page.getByText(reply,{exact:true})).toBeVisible();
 checks.push('Two independently signed-in members exchange a direct message and reply live; the reply persists after reload');
 await recipient.screenshot({path:join(evidence,'chief-platform-direct-chat.png')});
 const receipt={verifiedAt:new Date().toISOString(),scope:'Actual retained modules; synthetic Chief Acceptance organization only',checks,pending:['Tracker assignment/status and permission workflows','Team planner scheduling','Meeting, capture and agent follow-up workflows']};
 await writeFile(join(evidence,'chief-platform-modules.json'),JSON.stringify(receipt,null,2)+'\n');
 console.log(JSON.stringify(receipt));
} finally {await browser.close();}
